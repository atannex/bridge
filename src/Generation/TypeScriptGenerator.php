<?php

declare(strict_types=1);

namespace Atannex\Bridge\Generation;

use Atannex\Bridge\Contracts\HasInput;
use Atannex\Bridge\Contracts\HasOutput;
use Atannex\Bridge\Registry\Registry;
use Atannex\Bridge\Schema\Direction;
use Illuminate\Contracts\Container\Container;

/**
 * Writes the TypeScript contract for every registered operation and event.
 *
 * Output is deterministic: names are sorted, nothing time- or machine-
 * dependent is written, so `bridge:generate --check` can gate CI.
 */
final class TypeScriptGenerator
{
    public function __construct(
        private readonly Registry $registry,
        private readonly Container $container,
    ) {}

    public function generate(string $interface = 'AppBridge', string $module = '@atannex/bridge'): GeneratedContract
    {
        $writer = new TypeScriptWriter;
        $operations = [];
        $manifest = [];

        $actions = [];
        $outputs = [];

        // Outputs first, so a shared name such as `Product` goes to the shape
        // clients read; an input-only variant gets the `Input` suffix.
        foreach ($this->registry->operations() as $name => $definition) {
            $actions[$name] = $action = $this->container->make($definition->class);
            $writer->at($name.' output');
            $outputs[$name] = $action instanceof HasOutput ? $action->output()->nullableTypeScript($writer, Direction::Output) : 'null';
        }

        foreach ($this->registry->operations() as $name => $definition) {
            $action = $actions[$name];

            $writer->at($name.' input');
            $input = 'Record<string, never>';

            if ($action instanceof HasInput) {
                $schema = $action->input();

                if ($schema->isNullable()) {
                    $writer->error('The input schema must be a non-nullable Schema::object().');
                } else {
                    $input = $schema->typescript($writer, Direction::Input);
                }
            }

            $output = $outputs[$name];

            $doc = array_filter([
                $definition->description,
                $definition->deprecated !== null ? '@deprecated '.$definition->deprecated : null,
            ]);

            $operations[] = ($doc !== [] ? "/**\n * ".implode("\n * ", $doc)."\n */\n" : '')
                .TypeScriptWriter::quote($name).": {\ninput: {$input};\noutput: {$output};\n};";

            $manifest[] = TypeScriptWriter::quote($name).': { idempotency: '.TypeScriptWriter::quote($definition->idempotency->value)
                .', auth: '.TypeScriptWriter::quote($definition->authLabel())
                .', deprecated: '.($definition->deprecated !== null ? TypeScriptWriter::quote($definition->deprecated) : 'false').' },';
        }

        $events = [];

        foreach ($this->registry->events() as $name => $event) {
            $writer->at($name.' payload');
            $payload = $event->class::payloadSchema()->nullableTypeScript($writer, Direction::Output);
            $events[] = ($event->description !== null ? '/** '.str_replace('*/', '*\\/', $event->description)." */\n" : '')
                .TypeScriptWriter::quote($name).": {\nchannel: ".TypeScriptWriter::quote($event->channel).";\npayload: {$payload};\n};";
        }

        $writer->import('OperationsManifest');

        $lines = [
            '// Generated by atannex/bridge. Do not edit; run `php artisan bridge:generate`.',
            '/* eslint-disable */',
            '',
            'import type { '.implode(', ', $writer->imports()).' } from '.TypeScriptWriter::quote($module).';',
            '',
        ];

        foreach ($writer->declarations() as $name => $declaration) {
            $lines[] = $declaration['kind'] === 'interface'
                ? "export interface {$name} {$declaration['body']}"
                : "export type {$name} = {$declaration['body']};";
            $lines[] = '';
        }

        $lines[] = "export interface {$interface} {";
        $lines[] = 'operations: {';
        array_push($lines, ...$operations);
        $lines[] = '};';
        $lines[] = 'events: {';
        array_push($lines, ...$events);
        $lines[] = '};';
        $lines[] = '}';
        $lines[] = '';
        $lines[] = 'export const operations = {';
        array_push($lines, ...$manifest);
        $lines[] = '} as const satisfies OperationsManifest;';

        return new GeneratedContract(
            Indenter::indent(implode("\n", $lines))."\n",
            $writer->errors(),
            $writer->warnings(),
        );
    }
}
